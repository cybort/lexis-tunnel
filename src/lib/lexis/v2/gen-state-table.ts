/* Generates state-table.ts: empirical distribution of the rANS final state (x >> 28, virt)
 * when random bytes are mapped with the corpus frequency table. The frequency table is
 * key-independent (the key only permutes words), so one table serves every key.
 * Usage: node --import jiti/register src/lib/lexis/v2/gen-state-table.ts [frames] */
import { randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
import { CORPUS } from "./model.ts";
const freq: Uint32Array = CORPUS.freqByRank;
const cum = new Uint32Array(freq.length + 1);
for (let i = 0; i < freq.length; i++) cum[i + 1] = cum[i] + freq[i];
const M = 2 ** 24, L = 2 ** 32;
// slot -> symbol lookup via a coarse table
const coarse = new Uint32Array(1 << 12);
{ let s = 0; for (let i = 0; i < coarse.length; i++) { const slot = i << 12; while (cum[s + 1] <= slot) s++; coarse[i] = s; } }
const findSym = (slot: number) => { let s = coarse[slot >>> 12]; while (cum[s + 1] <= slot) s++; return s; };
const NB = 4080 * 4;
const counts = new Float64Array(NB);
const frames = Number(process.argv[2] || 1000000);
const pool = randomBytes(1 << 24); let pp = 0;
const rb = () => { if (pp >= pool.length) { randomBytes(pool.length).copy(pool); pp = 0; } return pool[pp++]; };
for (let t = 0; t < frames; t++) {
  const len = 20 + (rb() % 120);
  let x = L + ((rb() << 24) >>> 0) + (rb() << 16) + (rb() << 8) + rb(), pos = 4, virt = 0;
  while (pos < len) {
    const slot = x % M, s = findSym(slot);
    x = freq[s] * Math.floor(x / M) + slot - cum[s];
    while (x < L) { if (pos < len) { x = x * 256 + rb(); pos++; } else { x = x * 256 + rb(); virt++; } }
  }
  counts[(Math.floor(x / 2 ** 28) - 16) * 4 + virt]++;
}
const w = Array.from(counts, (c) => Math.round(c) + 1);
writeFileSync(new URL("./state-table.ts", import.meta.url), `// Generated by gen-state-table.ts from ${frames} simulated frames. Weights for (x >> 28, virt).\nexport const STATE_WEIGHTS = "${Buffer.from(Uint32Array.from(w).buffer).toString("base64")}";\n`);
console.log("frames", frames, "max", Math.max(...w), "min", Math.min(...w));
